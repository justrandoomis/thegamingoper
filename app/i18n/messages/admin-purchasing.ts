import { defineMessages, type MessageTree, type MessageValue } from "../translate";

/**
 * "admin-purchasing" — admin module 09, Suppliers and purchasing (app/routes/admin/purchasing). Arabic is the source;
 * English is the second admin language; Sorani exists for the catalogue test and needs a native reader.
 *
 * Written as side-by-side triples — m(ar, en, ckb) — so the three languages always have exactly the same keys; the
 * export below unfolds them into the usual { ar, en, ckb } trees. Error texts of the module's own codes live under
 * `errors` (the core's codes come from the "errors" namespace).
 */
type Leaf = { readonly leaf: true; ar: MessageValue; en: MessageValue; ckb: MessageValue };
type Tree = { [key: string]: Leaf | Tree };
const m = (ar: MessageValue, en: MessageValue, ckb: MessageValue): Leaf => ({ leaf: true, ar, en, ckb });
const isLeaf = (node: Leaf | Tree): node is Leaf => (node as Leaf).leaf === true;

function unfold(tree: Tree, locale: "ar" | "en" | "ckb"): MessageTree {
  const out: MessageTree = {};
  for (const [key, node] of Object.entries(tree)) out[key] = isLeaf(node) ? node[locale] : unfold(node, locale);
  return out;
}

